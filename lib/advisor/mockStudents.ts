function hashSeed(id: string): number {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) | 0;
  return Math.abs(h);
}

export function buildMockStudents(count = 100): StudentInsight[] {
  const out: StudentInsight[] = [];
  const states: StudentState[] = ["high", "fluctuating", "pressure"];
  const names = SAUDI_NAMES.slice(0, Math.min(count, SAUDI_NAMES.length));
  for (let i = 0; i < count; i++) {
    const id = String(i + 1);
    const name = names[i] ?? `طالب ${i + 1}`;
    const state = states[i % 3]!;
    const seed = hashSeed(id);
    const before = 55 + (seed % 38);
    const delta = state === "high" ? 3 + (seed % 12) : state === "fluctuating" ? -2 + (seed % 6) : -6 - (seed % 8);
    const after = Math.min(98, Math.max(45, before + delta));
    const pool = SIGNAL_POOLS[state][seed % SIGNAL_POOLS[state].length]!;
    out.push({
      id,
      name,
      before,
      after,
      state,
      signals: [...pool],
      recommendation: RECS[state][seed % RECS[state].length]!,
    });
  }
  return out;
}

